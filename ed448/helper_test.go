func seckeyOne(t *testing.T) *PrivateKey {
	t.Helper()
	priv, err := PrivateKeyFromBytes(rfc8032Test1Seed)
	if err != nil {
		t.Fatalf("PrivateKeyFromBytes failed for a valid seed: %v", err)
	}
	return priv
}

func seckeyN(t *testing.T, n byte) *PrivateKey {
	t.Helper()
	b := make([]byte, SeckeyLen)
	b[SeckeyLen-1] = n
	priv, err := PrivateKeyFromBytes(b)
	if err != nil {
		t.Fatalf("PrivateKeyFromBytes failed for a valid seed: %v", err)
	}
	return priv
}
